ORDER8 = ["吏部", "戶部", "禮部", "兵部", "刑部", "工部", "總督京儲", "都察院"]
ALIAS = {"萬鎧": "萬鏜", "范鐸": "范鐔"}


def norm(n):
    return ALIAS.get(n, n)


def dnames(year, office):
    return sorted(norm(r["person"]) for r in rows if r["year"] == year and r["office"] == office)


issues = []
stats = {"表头年": 0, "表头年衙数": 0, "一致衙": 0, "人名差异衙": 0, "整行差异衙": 0,
         "对页年": 0, "对页年行数": 0}

for year, spec in BOOK.items():
    stats["表头年"] += 1
    for off, book_names in spec["表头"].items():
        stats["表头年衙数"] += 1
        got = dnames(year, off)
        extra = sorted(set(got) - set(book_names))
        miss = sorted(set(book_names) - set(got))
        if not extra and not miss:
            stats["一致衙"] += 1
            continue
        # 若「多」与「缺」都是单名且不重叠 → 人名差异；否则整行差异
        if len(extra) == 1 and len(miss) == 1:
            stats["人名差异衙"] += 1
            kind = "人名"
        else:
            stats["整行差异衙"] += 1
            kind = "整行"
        issues.append({"级别": kind, "年": year, "衙署": off, "原书页": spec["page"],
                       "原书": book_names, "数据": got, "数据多": extra, "数据缺": miss,
                       "证据": f"docs/evidence/d04/pdf{spec['pdf']}.png"})

for year, order in BOOK_ORDERED.items():
    stats["对页年"] += 1
    whole = {r["person"] for r in rows if r["year"] == year}
    for i, book_names in enumerate(order):
        stats["对页年行数"] += 1
        miss_all = [n for n in book_names if n not in whole]
        if miss_all:
            issues.append({"级别": "整行（对页年）", "年": year, "衙署": ORDER8[i],
                           "原书": book_names, "全表缺": miss_all,
                           "备注": "对页续行：行→衙需合并对页才可判；此处仅记「全年表里都没有此人」"})

summary = {"stats": stats, "issues": len(issues)}
(ROOT / "_d04_summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=1), encoding="utf-8")

